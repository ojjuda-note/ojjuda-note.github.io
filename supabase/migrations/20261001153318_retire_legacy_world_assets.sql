-- Remove only recognized old item placements, keeping room metadata and any
-- unrecognized/new furniture. The helper exists for this transaction only.
create function pg_temp.without_retired_items(room jsonb)
returns jsonb language plpgsql security invoker set search_path = '' as $$
declare result jsonb := room;
begin
  if jsonb_typeof(room) <> 'object' then return room; end if;
  if jsonb_typeof(room->'items') = 'array' then
    result := jsonb_set(result, '{items}', coalesce((select jsonb_agg(item)
      from jsonb_array_elements(room->'items') item
      where not exists(select 1 from pg_temp.retired_world_types t where t.type=item->>'type')),'[]'::jsonb));
  end if;
  if jsonb_typeof(room->'rooms') = 'array' then
    result := jsonb_set(result, '{rooms}', coalesce((select jsonb_agg(pg_temp.without_retired_items(child))
      from jsonb_array_elements(room->'rooms') child),'[]'::jsonb));
  end if;
  if result->>'wp' in (select key from pg_temp.retired_world_keys) then result := result-'wp'; end if;
  if result->>'fl' in (select key from pg_temp.retired_world_keys) then result := result-'fl'; end if;
  return result;
end;
$$;

-- Pet-bank data has no purpose after the pet feature is removed. No balances,
-- ownership receipts, account appearance, photos, diaries or friendships reset.
do $$
declare balances_before jsonb;
begin
  select jsonb_object_agg(user_id, coins) into balances_before from public.user_private;
  update public.profiles set room=pg_temp.without_retired_items(room)
    where room is distinct from pg_temp.without_retired_items(room);
  update public.user_private set data=data-'petBank' where data ? 'petBank';
  if balances_before is distinct from (select jsonb_object_agg(user_id,coins) from public.user_private) then
    raise exception 'Legacy cleanup must preserve every wallet balance';
  end if;
end;
$$;
drop function pg_temp.without_retired_items(jsonb);
