create table ojjuda_arcade_internal.drinking_content_items (
 id integer generated always as identity primary key,
 kind text not null check (kind in ('bomb','liar','minority','mission','king','fingers','imagevote','initial')),
 body text not null,
 second text,
 active boolean not null default true,
 revision integer not null default 1 check (revision>0),
 queue_id integer unique references ojjuda_arcade_internal.drinking_prompt_queue(id),
 check ((second is not null) = (kind in ('mission','minority'))),
 check (length(body) between 1 and case kind when 'king' then 80 else 120 end),
 check (second is null or (length(second) between 1 and 120 and lower(second)<>lower(body))),
 check (kind<>'initial' or body ~ '^[ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ]{2}$')
);
-- A reversed choice pair means the same round.
create unique index drinking_content_unique on ojjuda_arcade_internal.drinking_content_items
 (kind,least(lower(body),lower(second)),greatest(lower(body),lower(second))) where active;
create index drinking_content_page on ojjuda_arcade_internal.drinking_content_items(kind,id) where active;
alter table ojjuda_arcade_internal.drinking_content_items enable row level security;
revoke all on ojjuda_arcade_internal.drinking_content_items from public,anon,authenticated;
revoke all on sequence ojjuda_arcade_internal.drinking_content_items_id_seq from public,anon,authenticated;

