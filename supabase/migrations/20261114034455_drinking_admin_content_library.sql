-- Only a moderator's approved transition publishes player submissions into the catalog.
create function ojjuda_arcade_internal.drinking_content_publish() returns trigger
language plpgsql security invoker set search_path='' as $$
begin
 update ojjuda_arcade_internal.drinking_content_items set queue_id=new.id
 where active and kind=new.kind and lower(body)=lower(new.body) and queue_id is null;
 if found then return new; end if;
 if exists(select 1 from ojjuda_arcade_internal.drinking_prompt_baseline where fingerprint=new.fingerprint) then
  raise exception 'duplicate_prompt';
 end if;
 insert into ojjuda_arcade_internal.drinking_content_items(kind,body,queue_id) values(new.kind,new.body,new.id);
 return new;
end;
$$;
