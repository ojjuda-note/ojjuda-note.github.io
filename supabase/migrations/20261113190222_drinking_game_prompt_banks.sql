create function ojjuda_arcade_internal.drinking_draw_prompt(p_kind text,p_previous text[])
returns text[] language plpgsql volatile security invoker set search_path='' as $draw$
declare
 last_slot integer;
 picked integer;
 blocked integer[];
 excluded integer;
 available integer;
 result text[];
begin
 -- The primary key finds the upper bound without reading every prompt.
 select slot into last_slot from ojjuda_arcade_internal.drinking_prompts
  where kind=p_kind order by slot desc limit 1;
 if last_slot is null then raise exception 'invalid_game'; end if;
 select coalesce(array_agg(slot order by slot),'{}'::integer[]) into blocked from ojjuda_arcade_internal.drinking_prompts
  where kind=p_kind and entry[1]=p_previous[1];
 available:=last_slot-cardinality(blocked);
 if available<=0 then raise exception 'no_alternative_prompt'; end if;
 -- Choose uniformly among allowed slots, skipping any with the previous first word.
 picked:=1+floor(random()*available)::int;
 foreach excluded in array blocked loop
  exit when excluded>picked;
  picked:=picked+1;
 end loop;
 select entry into strict result from ojjuda_arcade_internal.drinking_prompts where kind=p_kind and slot=picked;
 return result;
end;
$draw$;
