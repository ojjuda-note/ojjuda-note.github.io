const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {JSDOM}=require('jsdom');
const root=path.join(__dirname,'..');
const world=fs.readFileSync(path.join(root,'world.html'),'utf8');
const registry=world.match(/function worldRankGames\(\)\{[\s\S]*?(?=\nfunction openWorldBoardGame)/)[0];
const start=world.indexOf('var _r=')+'var _r='.length;
const catalog=world.slice(start,world.indexOf(',Z=3',start));
const tick=()=>new Promise(resolve=>setTimeout(resolve,0));
(async()=>{
 const dom=new JSDOM('<main data-board-root></main>',{url:'https://ojjuda.kr/world.html',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window,host=w.document.querySelector('main'),opened=[],requests=[];
 try{
  w.matchMedia=()=>({matches:false,addEventListener(){},removeEventListener(){}});
  w.ResizeObserver=class{observe(){}disconnect(){}};
  let captured=0;w.HTMLElement.prototype.setPointerCapture=()=>{captured++;};
  w.HTMLElement.prototype.scrollTo=function({left=0}){this.scrollLeft=left;};
  Object.defineProperty(w.HTMLElement.prototype,'clientWidth',{configurable:true,get(){return this.classList.contains('board-rank-groups')?400:0;}});
  Object.defineProperty(w.HTMLElement.prototype,'offsetLeft',{configurable:true,get(){return this.matches('[data-rank-group]')?[...this.parentElement.children].indexOf(this)*400:0;}});
  w.D={online:true,user:{id:'member'}};
  w.OjjudaMatgoAccess={visible:()=>false};
  w.eval('var _r='+catalog+';'+registry);
  w.eval(fs.readFileSync(path.join(root,'games/sacheonseong/ranking.js'),'utf8'));
  w.eval(fs.readFileSync(path.join(root,'world-game-rankings.js'),'utf8'));
  const query={select(){return this},eq(){return this},lte(){return this},order(){return this},range(){return Promise.resolve({data:[]})}};
  let wins=9,delay=false,release;
  const client={from:()=>query,schema:()=>({rpc:async()=>({data:[]})}),rpc:async(name,args)=>{
   if(name!=='community_game_monthly_leaders')return {data:{allowed:false}};
   requests.push(args.p_games);
   if(delay)await new Promise(resolve=>{release=resolve});
   return {data:Object.fromEntries(args.p_games.map(id=>[id,id==='tank'?{nick:'시험회원',score:wins,source:'tank_wins'}:null]))};
  }};
  w.OjjudaGameRankings.mount(host,{client,owner:'member',games:w.worldRankGames(),onOpenGame:id=>opened.push(id)});
  await tick();await tick();
  const tank=()=>host.querySelector('[data-game=tank]');
  const multi=()=>host.querySelector('[data-rank-group=multi]');
  const currentPage=()=>Number(multi().dataset.rankPage);
  const visibleTank=()=>multi().getAttribute('aria-hidden')==='false'&&tank().closest('.board-rank-page').getAttribute('aria-hidden')==='false';
  function nextPage(){
   multi().querySelector('.board-rank-controls button:last-child').click();
  }
  assert.ok(host.querySelectorAll('[data-game=tank]').length>=1,'the real game catalog includes Tank');
  assert.equal(host.querySelector('[data-rank-group=solo] [data-game=tank]'),null,'Tank stays in multiplayer even when pages wrap');
  for(const page of multi().querySelectorAll('.board-rank-page'))assert.ok(page.querySelectorAll('[data-game=tank]').length<=1,'Tank never appears twice on the same page');
  assert.equal(tank().querySelector('.board-leader-score').textContent,'9연승');
  assert.equal(visibleTank(),false,'the initial carousel shows only the solo category');
  const categories=host.querySelector('.board-rank-groups');
  categories.scrollLeft=400;categories.dispatchEvent(new w.Event('scroll'));await tick();
  assert.equal(categories.dataset.rankCategory,'multi','native horizontal scrolling opens multiplayer');
  const inner=multi().querySelector('.board-rank-viewport');
  inner.dispatchEvent(new w.MouseEvent('pointerdown',{bubbles:true,button:0,clientX:200,clientY:20}));
  inner.dispatchEvent(new w.MouseEvent('pointerup',{bubbles:true,button:0,clientX:20,clientY:20}));
  assert.equal(captured,0,'the inner table does not capture horizontal gestures');
  assert.equal(currentPage(),0,'a horizontal gesture cannot also change the inner game page');
  assert.ok(visibleTank(),'Tank wins appear on the first ranking page');
  tank().querySelector('button').click();await tick();assert.deepEqual(opened,['tank']);
  nextPage();assert.equal(currentPage(),1);assert.equal(visibleTank(),false);
  assert.equal(host.querySelector('[data-rank-group=solo]').dataset.rankPage,'0','multiplayer paging leaves the solo card in place');
  const before=requests.length;
  w.document.body.classList.add('gaming');await tick();
  wins=10;delay=true;
  w.dispatchEvent(new w.CustomEvent('ojjuda:game-record-saved',{detail:{owner:'member',game:'tank'}}));
  assert.equal(requests.length,before,'keep the game open while its result is saved');
  w.document.body.classList.remove('gaming');await tick();
  assert.equal(typeof release,'function');delay=false;release();await tick();await tick();
  assert.equal(tank().querySelector('.board-leader-score').textContent,'10연승');
  assert.ok(visibleTank(),'returning from Tank reveals its refreshed ranking, even from a later page');
  assert.equal(host.querySelector('.board-rank-groups').dataset.rankCategory,'multi','a saved Tank result selects multiplayer');
  assert.equal(requests.length,before+1,'refresh all rankings in one request');
  nextPage();const retained=currentPage();await w.OjjudaGameRankings.refresh();
  assert.equal(currentPage(),retained,'ordinary refresh preserves the selected page');
  w.dispatchEvent(new w.CustomEvent('ojjuda:game-record-saved',{detail:{owner:'another-member',game:'tank'}}));await tick();
  assert.equal(currentPage(),retained,'another member cannot change the selected page');
  wins=0;await w.OjjudaGameRankings.refresh();assert.equal(tank().querySelector('.board-leader-score').textContent,'—');
  assert.equal(tank().querySelector('.board-leader-nick').textContent,'이번 달 기록 없음');
  assert.equal(tank().querySelector('.board-score-value'),null,'zero wins do not create a ranked record');
  assert.equal(currentPage(),retained,'hiding a zero record preserves the selected page');
  console.log('PASS: real Tank catalog, wins, game opening, return-page selection, delayed response, ordinary refresh and account isolation');
 }finally{w.OjjudaGameRankings?.mount(null);w.close();}
})().catch(error=>{console.error(error);process.exitCode=1});
