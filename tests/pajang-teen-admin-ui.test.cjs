const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {execFileSync}=require('node:child_process');
const {test}=require('node:test');
const root=path.join(__dirname,'..');

test('teen content moderation screen requires administrator confirmation and uses safe DOM text',()=>{
  const script=path.join(root,'admin/pajang-teen.js');
  execFileSync(process.execPath,['--check',script],{stdio:'pipe'});
  const code=fs.readFileSync(script,'utf8');
  const page=fs.readFileSync(path.join(root,'admin/pajang-teen.html'),'utf8');
  const style=fs.readFileSync(path.join(root,'admin/pajang-teen.css'),'utf8');
  assert.match(code,/auth\.getUser/);
  assert.match(code,/from\('app_admins'\)/);
  assert.match(code,/admin_pajang_teen_moderation/);
  assert.match(code,/admin_pajang_teen_comments/);
  assert.match(code,/approved|approve/);
  assert.match(code,/hide/);
  assert.match(code,/resolve-report/);
  assert.match(code,/원문 숨김/);
  assert.match(code,/r\.draftId/);
  assert.match(code,/r\.commentId/);
  assert.match(code,/r\.body/);
  assert.match(code,/\.textContent/);
  assert.ok(!code.includes('.innerHTML'),'untrusted answers must never be HTML');
  assert.match(page,/\/admin\/pajang-teen\.js/);
  assert.match(page,/\/admin\/pajang-teen\.css/);
  assert.ok(style.includes('min-height:44px'),'tappable controls');
  assert.ok(!code.includes('service_role'),'admin client must not use a privileged key');
});
