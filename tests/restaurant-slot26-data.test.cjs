'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'games/certified-restaurants');
const read=name=>JSON.parse(fs.readFileSync(path.join(dir,name),'utf8'));
const slot=read('official-chungnam-slot26.json'),base=read('restaurants.json'),source=read('sources.json');
const audit=JSON.parse(fs.readFileSync(path.join(root,'ops/restaurant-region-audit.json'),'utf8'));
const app=fs.readFileSync(path.join(dir,'app.js'),'utf8');
const sidecars=fs.readdirSync(dir).filter(name=>/^official-.*\.json$/.test(name));
const all=[...base.restaurants,...sidecars.flatMap(name=>read(name).restaurants||[])];
assert.equal(slot.restaurants.length,7);
assert.ok(all.length>=3182);
assert.equal(new Set(all.map(row=>row.id)).size,all.length);
assert.deepEqual(slot.restaurants.map(row=>row.district).sort(),['계룡시','계룡시','공주시','공주시','논산시','논산시','논산시']);
for(const row of slot.restaurants){
 assert.match(row.id,/^local-chungnam-slot26-/);
 assert.equal(row.region,'충남');
 assert.ok(row.address.startsWith('충청남도 '+row.district+' '));
 assert.equal(row.lat,null);assert.equal(row.lng,null);
 assert.equal(row.guides.length,1);
 const guide=row.guides[0];
 assert.equal(guide.provider,'local-guide');
 assert.equal(guide.year,null);
 assert.ok(['listing','selection'].includes(guide.yearType));
 assert.equal(guide.status,'official_publication_listing');
 assert.ok(/^https:\/\//.test(guide.sourceUrl));
 assert.ok(/^https:\/\//.test(row.addressSourceUrl));
 assert.ok(!row.coordinateSource);
}
assert.ok(app.includes("fetch('./official-chungnam-slot26.json?v="));
assert.ok(app.includes('...slot26.restaurants'));
assert.ok(app.includes('slot26Response.json()'));
const log=audit.entries.filter(entry=>entry.cycle===1&&entry.slot===26);
assert.equal(log.length,1);
assert.equal(log[0].additions,7);
assert.equal(log[0].modifications,0);
assert.equal(log[0].locationCoordinatesAdded,0);
assert.equal(log[0].locationHidden,0);
assert.equal(log[0].locationPending,13);
assert.equal(log[0].locationReviews.length,13);
assert.ok(source.coverageAuditHistory.some(entry=>entry.id==='2026-11-06-chungnam-slot26-provincial-tourism-7'&&entry.newRestaurantCount===7));
assert.ok(source.coverageAuditHistory.find(entry=>entry.id==='2026-11-06-chungnam-slot26-provincial-tourism-7').currentCoverage.uniqueRestaurants>=3182);
const version=fs.readFileSync(path.join(root,'world-game-assets.js'),'utf8').match(/restaurants:'(\d+)\.(\d+)\.(\d+)'/);
assert.ok(version&&(Number(version[1])*1000000+Number(version[2])*1000+Number(version[3]))>=1009032);
const release=JSON.parse(fs.readFileSync(path.join(root,'game-release.json'),'utf8')).revision;
assert.ok(fs.readFileSync(path.join(root,'world.html'),'utf8').includes('world-game-assets.js?v='+release));
assert.match(fs.readFileSync(path.join(dir,'index.html'),'utf8'),/app\.js\?v=\d{8}-restaurants-/);
console.log('restaurant slot26 verified');
