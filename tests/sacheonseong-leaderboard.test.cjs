const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {JSDOM}=require('jsdom');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const tick=()=>new Promise(resolve=>setImmediate(resolve));
(async()=>{
 const dom=new JSDOM('<main></main>',{url:'https://ojjuda.kr/world.html',runScripts:'outside-only',pretendToBeVisual:true});
 const w=dom.window;
 try{
  w.matchMedia=()=>({matches:true,addEventListener(){},removeEventListener(){}});
  w.ResizeObserver=class{observe(){}disconnect(){}};
  w.eval(read('games/sacheonseong/ranking.js'));w.eval(read('world-game-rankings.js'));
  const R=w.OjjudaSacheonseongRanking,host=w.document.querySelector('main'),requests=[],opened=[];
  let winner={nick:'높은 단계',stage:4,score:R.score(79560)};
  const client={rpc:async(name,args)=>{assert.equal(name,'community_game_monthly_leaders');requests.push([...args.p_games]);return {data:{sacheonseong:winner}};}};
  w.OjjudaGameRankings.mount(host,{client,owner:'viewer',games:{sacheonseong:{name:'사천성',unit:'초',rankingBasis:'stage_time'}},onOpenGame:id=>opened.push(id)});
  await tick();await tick();
  let row=host.querySelector('[data-game=sacheonseong]');
  assert.deepEqual(requests,[['sacheonseong']],'query all stages as one game');
  assert.equal(host.querySelectorAll('select').length,0,'no default stage filter');
  assert.equal(row.querySelector('.board-leader-nick').textContent,'높은 단계');
  assert.match(row.querySelector('.board-game-difficulty').textContent,/4단계/);
  assert.equal(row.querySelector('.board-leader-score').textContent,'01:19.56');
  assert.match(row.querySelector('th').title,/최고 완료 단계/);
  row.querySelector('button').click();await tick();assert.deepEqual(opened,['sacheonseong']);
  winner={nick:'다음 최고 기록',stage:10,score:R.score(182340)};
  w.dispatchEvent(new w.CustomEvent('ojjuda:game-record-saved',{detail:{owner:'viewer',game:'sacheonseong',stage:1}}));
  await tick();await tick();row=host.querySelector('[data-game=sacheonseong]');
  assert.deepEqual(requests.at(-1),['sacheonseong'],'finishing stage 1 must not filter the leaderboard to stage 1');
  assert.match(row.querySelector('.board-game-difficulty').textContent,/10단계/);
  assert.equal(row.querySelector('.board-leader-score').textContent,'03:02.34');
  w.OjjudaGameRankings.mount(null);
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  w.HTMLDialogElement.prototype.close=function(){this.open=false;};
  w.eval(read('world-sacheonseong-game.js'));
  const queried=[];
  w.OjjudaSacheonseongGame.open({onRanking:async stage=>{queried.push(stage);return [winner];}});
  w.document.querySelector('.ge-primary').click();
  const child=w.document.querySelector('.sacheonseong-game-dialog iframe').contentWindow;
  child.document.write('<body><p id="server-note"></p><button id="retry-records"></button><button id="online-ranking"></button><dialog id="modal"><div id="modal-content"></div></dialog></body>');
  child.document.close();
  child.HTMLDialogElement.prototype.showModal=function(){this.open=true;};
  child.postMessage=data=>child.dispatchEvent(new child.MessageEvent('message',{data,origin:w.location.origin,source:w}));
  w.postMessage=data=>w.dispatchEvent(new w.MessageEvent('message',{data,origin:w.location.origin,source:child}));
  child.eval(read('games/sacheonseong/ranking.js'));child.eval(read('games/sacheonseong/server.js'));
  child.document.getElementById('online-ranking').click();await tick();await tick();
  assert.deepEqual(queried,[0],'game modal asks its bridge for the overall ranking');
  assert.equal(child.document.querySelectorAll('select').length,0);
  assert.match(child.document.querySelector('.online-rank-result').textContent,/10단계 03:02.34/);
  assert.match(child.document.getElementById('modal-content').textContent,/한 사람당 하나/);
  w.OjjudaSacheonseongGame.close();
  console.log('PASS: one overall winner, highest-stage label, clear time, game opening and unfiltered refresh.');
 }finally{w.OjjudaGameRankings?.mount(null);w.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
