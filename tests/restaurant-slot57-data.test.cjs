'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));

const db = read('games/certified-restaurants/restaurants.json');
const sidecar = read('games/certified-restaurants/official-jeju-slot57.json');
const sources = read('games/certified-restaurants/sources.json');
const audit = read('ops/restaurant-region-audit.json');
const app = fs.readFileSync(path.join(root, 'games/certified-restaurants/app.js'), 'utf8');
const assets = fs.readFileSync(path.join(root, 'shared/games/world-game-assets.js'), 'utf8');
const world = fs.readFileSync(path.join(root, 'world.html'), 'utf8');
const index = fs.readFileSync(path.join(root, 'games/certified-restaurants/index.html'), 'utf8');
const release = read('game-release.json');

assert.equal(sidecar.cycle, 1);
assert.equal(sidecar.slot, 57);
assert.equal(sidecar.restaurants.length, 7);
assert.equal(sidecar.locationEnrichments.length, 1);
const ids = new Set(db.restaurants.map(item => item.id));
const names = new Set(db.restaurants.filter(item => item.region === '제주').map(item => item.name.replace(/\s/g, '')));
for (const item of sidecar.restaurants) {
  assert.ok(!ids.has(item.id), 'new place IDs must not collide with saved IDs');
  assert.ok(!names.has(item.name.replace(/\s/g, '')), 'new Jeju listing must not duplicate the existing catalog');
  ids.add(item.id); names.add(item.name.replace(/\s/g, ''));
  assert.equal(item.region, '제주'); assert.equal(item.district, '제주시');
  assert.ok(item.address.startsWith('제주특별자치도 제주시 '));
  assert.ok(Number.isFinite(item.lat) && item.lat > 33 && item.lat < 34);
  assert.ok(Number.isFinite(item.lng) && item.lng > 126 && item.lng < 127);
  assert.equal(item.guides.length, 1);
  assert.equal(item.guides[0].provider, 'local-guide');
  assert.equal(item.guides[0].year, null);
  assert.equal(item.guides[0].yearType, 'listing');
  assert.match(item.guides[0].sourceUrl, /^https:\/\/www\.visitjeju\.net\/kr\/detail\/view\?contentsid=(?:CNTS_|CONT_)/);
  assert.equal(item.guides[0].sourceUrl, item.coordinateSource.url);
  assert.equal(item.coordinateSource.checkedAt, '2026-11-08');
}
const [patch] = sidecar.locationEnrichments;
const original = db.restaurants.find(item => item.id === patch.id);
assert.ok(original && original.region === '제주' && original.district === '제주시');
assert.equal(original.name, patch.expectedName); assert.equal(original.address, patch.expectedAddress);
assert.equal(original.lat, null); assert.equal(original.lng, null);
assert.ok(Number.isFinite(patch.lat) && Number.isFinite(patch.lng));
assert.ok(original.guides.some(g => g.provider === 'local-guide' || g.provider === 'blue-ribbon'));
assert.match(patch.coordinateSource.url, /^https:\/\/www\.visitjeju\.net\/kr\/detail\/view\?contentsid=CNTS_/);

assert.match(app, /slot57Jeju\.restaurants/);
assert.match(app, /slot57Jeju\.locationEnrichments/);
assert.match(app, /row\.id === patch\.id && row\.name === patch\.expectedName && row\.address === patch\.expectedAddress/);
assert.match(app, /restaurant\.lat != null \|\| restaurant\.lng != null/);
assert.match(app, /official-jeju-slot57\.json\?v=\d{8}-restaurants-[a-z0-9-]+/);
assert.match(index, /\.\/app\.js\?v=\d{8}-restaurants-[a-z0-9-]+/);
assert.ok(assets.includes("const revision='" + release.revision + "'"));
assert.ok(world.includes('/shared/games/world-game-assets.js?v=' + release.revision));

const auditRow = sources.coverageAuditHistory.find(row => row.cycle === 1 && row.slot === 57);
assert.ok(auditRow, 'slot57 audit history must persist across future releases');
assert.equal(auditRow.cycle, 1); assert.equal(auditRow.slot, 57);
assert.equal(auditRow.newRestaurantCount, sidecar.restaurants.length);
assert.equal(auditRow.modificationCount, 1);
assert.equal(auditRow.coordinateAddedCount, sidecar.restaurants.length + sidecar.locationEnrichments.length);
assert.equal(auditRow.locationExcludedCount, 0);
assert.deepEqual(sources.coverage, sources.latestCoverageAudit.currentCoverage);
assert.equal(auditRow.currentCoverage.uniqueRestaurants - auditRow.previousCoverage.uniqueRestaurants, 7);
assert.equal(auditRow.currentCoverage.coordinatesAvailable - auditRow.previousCoverage.coordinatesAvailable, 8);
assert.equal(auditRow.currentCoverage.coordinatesMissing - auditRow.previousCoverage.coordinatesMissing, -1);
assert.equal(auditRow.currentCoverage.regionalCounts['제주'] - auditRow.previousCoverage.regionalCounts['제주'], 7);
assert.equal(Object.values(sources.coverage.categoryCounts).reduce((sum, n) => sum + n, 0), sources.coverage.uniqueRestaurants);
const entry = audit.entries.find(row => row.cycle === 1 && row.slot === 57);
assert.ok(entry, 'slot57 retains a committed audit record');
assert.equal(entry.additions, 7); assert.equal(entry.modifications, 1);
assert.equal(entry.locationCoordinatesAdded, 8); assert.equal(entry.locationHidden, 0);
assert.equal(entry.locationPending, entry.pendingLocationInventory.length);
assert.ok(entry.pendingLocationInventory.length > 0);
assert.ok(entry.pendingLocationInventory.every(row => row.restaurantId && row.name && row.region && row.recheckSlot === 57 && row.recheckCycle === 2));
assert.ok(!entry.pendingLocationInventory.some(row => row.restaurantId === patch.id || sidecar.restaurants.some(item => item.id === row.restaurantId)));
assert.equal(sources.jejuSlot57.sourceFile, 'games/certified-restaurants/official-jeju-slot57.json');
console.log('Jeju slot57 verified official listings, exact coordinates and audit reconciliation passed');
