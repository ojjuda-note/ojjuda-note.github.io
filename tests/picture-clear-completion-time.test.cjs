const {test}=require('node:test');
const assert=require('node:assert/strict');
const {readFileSync}=require('node:fs');
const {resolve}=require('node:path');
const {PGlite}=require('@electric-sql/pglite');
const read=file=>readFileSync(resolve(__dirname,'../supabase/migrations',file),'utf8');
const monthly=read('20261031085535_monthly_game_rankings_archive.sql');
const spot=read('20261022130306_multiplayer_ranking_details.sql');
const motion=read('20261112050656_spot_motion_stage_collection.sql');
const photo=read('20261006082621_photo_ttang_monthly_ranking.sql');
const sql=read('20261117235500_picture_clear_completion_times.sql');
test('picture retries keep their original period, caller, distinct stage and access rules',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 const member='10000000-0000-0000-0000-000000000001', other='10000000-0000-0000-0000-000000000002';
 await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema ojjuda_ranking_internal;
   create schema ojjuda_photo_internal;create schema ojjuda_guest_internal;
   create table auth.users(id uuid primary key);create table public.profiles(id uuid primary key);
   create table public.photo_stages(id uuid,owner uuid,status text,visibility text,created_at timestamptz);
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('app.actor',true),'')::uuid$$;
   create function public.is_banned(uuid) returns boolean language sql stable as $$select false$$;
   create function public.photo_is_admin() returns boolean language sql as $$select false$$;
   create function public.photo_is_friend(uuid,uuid) returns boolean language sql as $$select false$$;
   create function ojjuda_photo_internal.member_allowed() returns boolean language sql as $$select current_setting('app.adult',true)='yes'$$;
   grant usage on schema public,auth,ojjuda_guest_internal,ojjuda_photo_internal to anon,authenticated;
   insert into auth.users values('${member}'),('${other}');insert into profiles select id from auth.users;`);
 await db.exec(monthly.slice(monthly.indexOf('create function ojjuda_ranking_internal.month_key'),monthly.indexOf('create function ojjuda_ranking_internal.month_start')));
 await db.exec(monthly.slice(monthly.indexOf('create table ojjuda_ranking_internal.settings'),monthly.indexOf('-- Separate monthly ledgers')));
 await db.exec(monthly.slice(monthly.indexOf('create table ojjuda_ranking_internal.picture_clears'),monthly.indexOf('create index ranking_picture_period')));
 await db.exec(spot.slice(spot.indexOf('create table ojjuda_guest_internal.spot_clears'),spot.indexOf('create function ojjuda_guest_internal.record_spot_clear')));
 await db.exec(motion.slice(motion.indexOf('alter table ojjuda_guest_internal.spot_clears'),motion.indexOf('do $stages$')));
 await db.exec(photo.slice(photo.indexOf('create table if not exists ojjuda_photo_internal.game_clears'),photo.indexOf('create or replace function ojjuda_photo_internal.record_game_clear')));
 await db.exec("update ojjuda_ranking_internal.settings set first_month='2020-01-01';");
 await db.exec(sql);
 const value=async(q,params)=>(await db.query(q,params)).rows[0].result;
 const before='2025-02-01T00:59:59+09:00',after='2025-02-01T01:00:00+09:00',token='a'.repeat(64);
 const record=(stage,date,actor,tok=null)=>value('select public.record_spot_clear_at($1,$2,$3,$4) result',[stage,date,actor,tok]);
 const picture=(stage,date,actor)=>value('select public.record_photo_ttang_clear_at($1,$2,$3) result',[stage,date,actor]);
 await db.exec("set role anon");
 assert.equal((await record(182,before,null,token)).score,1);
 assert.equal((await record(182,before,null,token)).duplicate,true);
 assert.equal((await record(182,after,null,token)).duplicate,false);
 assert.equal((await record(183,before,null,token)).ok,false);
 assert.equal((await record(1,before,member,token)).ok,false);
 await assert.rejects(picture('39',before,null),/permission denied/);
 await db.exec(`reset role;set role authenticated;set app.actor='${member}';set app.adult='yes';`);
 assert.equal((await record(182,before,member)).duplicate,false);
 assert.equal((await picture('39',before,member)).previous_period,true);
 assert.equal((await picture('39',before,member)).score,1);
 assert.equal((await picture('39',after,member)).score,1);
 assert.equal((await picture('38',after,member)).score,2);
 assert.equal((await picture('37',after,other)).reason,'account_changed');
 await assert.rejects(picture('40',after,member),/invalid_stage/);
 assert.equal((await record(3,'infinity',member)).ok,false);
 assert.equal((await record(3,'2000-01-01',member)).ok,false);
 await db.exec("set app.adult='no'");await assert.rejects(picture('1',before,member),/not_allowed/);
 await db.exec("reset role");
 assert.equal(await value("select count(*)::int result from ojjuda_ranking_internal.picture_clears where month_start='2025-01-01'"),3);
 assert.equal(await value("select count(*)::int result from ojjuda_ranking_internal.picture_clears where month_start='2025-02-01'"),3);
 assert.equal(await value("select count(*)::int result from ojjuda_photo_internal.game_clears where month_start='2025-02-01'"),2);
});
