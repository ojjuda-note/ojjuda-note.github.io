const test=require('node:test'),assert=require('node:assert/strict');
const {fixture}=require('./yut-public-room-fixture.cjs');
const key=i=>'B'+String(i).padStart(86,'A');
test('public Yut directory enforces member seats, capacity, ownership and public projections',async()=>{
  const f=await fixture(),[A,B,C,D,E,F,G,H,I,J,BANNED,ANON]=f.users;
  const create=(actor,seed,extra={})=>f.call(actor,'create',null,{title:'윷놀이 badword',capacity:2,key:key(seed),request_id:crypto.randomUUID(),...extra});
  try{
    await assert.rejects(()=>create(null,1),/not_signed_in/);
    await assert.rejects(()=>create(BANNED,1),/banned/);
    await assert.rejects(()=>create(ANON,1),/not_signed_in/);
    await assert.rejects(()=>f.call(A,'list',null,{},'anon'),/permission denied/);
    await assert.rejects(()=>f.as(A,'select * from ojjuda_yut_internal.rooms'),/permission denied/);
    const request=crypto.randomUUID(),a=(await create(A,1,{request_id:request})).room;
    assert.equal(a.room_no,1001);assert.equal(a.title,'윷놀이 ❤️❤️');
    assert.equal(a.players[0].name,'하나 ❤️❤️');assert.equal(a.players[0].key,key(1));
    assert.deepEqual(a.setup,{count:2,mode:'island',offset:2,counts:[4,4],animals:[2,5]});
    const again=(await create(A,1,{title:'ignored',request_id:request})).room;
    assert.deepEqual(again,a,'a lost create response reuses the same public room');
    await assert.rejects(()=>create(A,9,{request_id:request}),/room_identity_mismatch/);
    await assert.rejects(()=>create(A,9),/room_in_progress/);
    await assert.rejects(()=>create(B,2,{capacity:9}),/invalid_capacity/);
    await assert.rejects(()=>create(B,2,{title:'가'.repeat(41)}),/invalid_title/);
    await assert.rejects(()=>create(B,2,{setup:{counts:[1,4]}}),/invalid_options/);
    await assert.rejects(()=>create(B,2,{setup:{animals:[1,13]}}),/invalid_options/);
    const listed=await f.list(B);
    assert.deepEqual(listed.filter(r=>r.kind!=='yut').map(r=>r.kind),['poker','bang','roulette','onecard']);
    const card=listed.find(r=>r.kind==='yut');
    assert.equal(card.players,1);assert.equal(card.capacity,2);assert.equal(card.native,true);
    assert.equal(card.code,String(a.room_no));assert.equal(card.is_member,false);
    assert.ok(!JSON.stringify(card).includes(key(1))&&!JSON.stringify(card).includes(A),'spectator projection exposes no signing keys or UUIDs');
    assert.equal((await f.call(A,'list')).mine.room_no,a.room_no);
    await assert.rejects(()=>f.call(C,'heartbeat',a.room_no),/not_room_member/);
    await assert.rejects(()=>f.call(C,'leave',a.room_no),/not_room_member/);
    const joined=(await f.call(B,'join',a.room_no,{key:key(2)})).room;
    assert.deepEqual(joined.players.map(p=>p.key),[key(1),key(2)]);
    assert.equal((await f.call(B,'join',a.room_no,{key:key(2)})).room.players.length,2);
    await assert.rejects(()=>f.call(B,'join',a.room_no,{key:key(3)}),/room_identity_mismatch/);
    await assert.rejects(()=>f.call(C,'join',a.room_no,{key:key(3)}),/room_full/);
    await assert.rejects(()=>f.call(B,'start',a.room_no,{keys:[key(1),key(2)]}),/not_room_owner/);
    await assert.rejects(()=>f.call(A,'start',a.room_no,{keys:[key(1)]}),/state_conflict/);
    const started=(await f.call(A,'start',a.room_no,{keys:[key(1),key(2)]})).room;
    assert.equal(started.status,'playing');
    await assert.rejects(()=>f.call(C,'join',a.room_no,{key:key(3)}),/room_already_started/);
    await f.call(B,'leave',a.room_no);
    const left=(await f.call(A,'heartbeat',a.room_no)).room;
    assert.equal(left.players[1].departed,true);assert.equal(left.players[1].key,key(2),'active seat order stays fixed');
    await assert.rejects(()=>f.call(B,'join',a.room_no,{key:key(2)}),/room_unavailable/);
    await f.call(A,'leave',a.room_no);
    assert.equal((await f.call(C,'list')).rooms.length,0);
    await assert.rejects(()=>f.call(B,'heartbeat',a.room_no),/room_unavailable/);
    const b=(await create(B,4,{capacity:3})).room;
    await f.call(C,'join',b.room_no,{key:key(5)});
    await f.call(C,'leave',b.room_no);
    assert.equal((await f.call(B,'heartbeat',b.room_no)).room.players.length,1);
    await assert.rejects(()=>f.call(B,'start',b.room_no,{keys:[key(4)]}),/need_players/);
    assert.equal((await f.call(B,'start',b.room_no,{keys:[key(4)],fill_bots:true})).room.status,'playing');
    const c=(await create(C,6)).room;
    await f.db.query('insert into fixture.blocks values($1,$2)',[C,D]);
    assert.ok(!(await f.call(D,'list')).rooms.some(r=>r.room_no===c.room_no));
    await assert.rejects(()=>f.call(D,'join',c.room_no,{key:key(7)}),/room_unavailable/);
    await f.call(E,'join',c.room_no,{key:key(8)});
    await f.db.query("update ojjuda_yut_internal.members set expires_at=clock_timestamp()-interval '1 second' where user_id=$1",[E]);
    const reclaimed=(await f.call(F,'join',c.room_no,{key:key(9)})).room;
    assert.deepEqual(reclaimed.players.map(p=>p.key),[key(6),key(9)],'expired waiting seats can be reclaimed');
    await f.db.query("update ojjuda_yut_internal.rooms set expires_at=clock_timestamp()-interval '1 second' where room_no=$1",[c.room_no]);
    await assert.rejects(()=>f.call(C,'heartbeat',c.room_no),/room_unavailable/);
    assert.ok(!(await f.call(G,'list')).rooms.some(r=>r.room_no===c.room_no));
    const d=(await create(H,10)).room;
    await f.call(I,'join',d.room_no,{key:key(11)});
    await assert.rejects(()=>create(I,12),/room_in_progress/);
    await f.call(H,'start',d.room_no,{keys:[key(10),key(11)]});
    await f.db.query("update ojjuda_yut_internal.members set expires_at=clock_timestamp()-interval '1 second' where user_id=$1",[I]);
    assert.equal((await f.call(H,'heartbeat',d.room_no)).room.players[1].departed,true,'disconnected players release their active seats to the computer');
    await f.db.query('insert into fixture.bans values($1)',[H]);
    assert.ok(!(await f.call(J,'list')).rooms.some(r=>r.room_no===d.room_no));
    await assert.rejects(()=>f.call(I,'heartbeat',d.room_no),/room_unavailable/);
  }finally{await f.close();}
});
