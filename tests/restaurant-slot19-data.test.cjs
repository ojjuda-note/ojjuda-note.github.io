'use strict';
const a = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const root = path.resolve(__dirname, '..'), directory = path.join(root, 'games/certified-restaurants');
const read = name => JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8'));
const slot = read('official-gangwon-slot19.json'), base = read('restaurants.json'), sources = read('sources.json');
const audit = JSON.parse(fs.readFileSync(path.join(root, 'ops/restaurant-region-audit.json'), 'utf8'));
const app = fs.readFileSync(path.join(directory, 'app.js'), 'utf8');
const sidecars = fs.readdirSync(directory).filter(name => /^official-.*\.json$/.test(name));
const all = [...base.restaurants, ...sidecars.flatMap(name => read(name).restaurants || [])];
a.equal(slot.restaurants.length, 4);
a.equal(all.length, 3157);
a.equal(new Set(all.map(x => x.id)).size, all.length);
a.deepEqual(slot.restaurants.map(x => x.name), ['강릉풍년갈비', '피아노', '뜰애', '영빈관']);
for (const item of slot.restaurants) {
  a.equal(item.region, '강원');
  a.ok(item.address.startsWith('강원특별자치도 ' + item.district + ' '));
  a.equal(item.guides.length, 1);
  a.equal(item.guides[0].provider, 'local-guide');
  a.equal(item.guides[0].year, null);
  a.equal(item.guides[0].yearType, 'listing');
  a.ok(/^https:\/\//.test(item.guides[0].sourceUrl));
  a.equal(item.lat === null, item.lng === null);
}
const gangneung = slot.restaurants[0];
a.equal(gangneung.guides[0].status, 'official_tourism_listing');
a.equal(gangneung.address, '강원특별자치도 강릉시 강릉대로587번길 10-5');
a.ok(Number.isFinite(gangneung.lat) && Number.isFinite(gangneung.lng));
a.match(gangneung.coordinateSource.url, /^https:\/\/smi\.purpleo\.kr\//);
const donghae = slot.restaurants.slice(1);
a.ok(donghae.every(x => x.district === '동해시' && x.lat === null && x.lng === null));
a.ok(donghae.every(x => x.guides[0].status === 'official_municipal_designation' && x.guides[0].sourceAsOf === '2026-04-30'));
a.ok(app.includes("fetch('./official-gangwon-slot19.json?v=20261106-restaurants-slot19-1"));
a.ok(app.includes('...slot19.restaurants'));
a.equal(sources.coverage.uniqueRestaurants, 3157);
a.equal(sources.coverage.coordinatesAvailable, 1029);
a.equal(sources.coverage.coordinatesMissing, 2128);
a.equal(sources.coverage.regionalCounts['강원'], 56);
a.equal(sources.localGovernment.municipalSelection20261106GangwonSlot19.recordCount, 4);
a.equal(sources.latestCoverageAudit.newRestaurantCount, 4);
const log = audit.entries.find(x => x.cycle === 1 && x.slot === 19);
a.ok(log); a.equal(log.additions, 4); a.equal(log.modifications, 0);
a.equal(log.locationCoordinatesAdded, 1); a.equal(log.locationHidden, 0);
a.equal(log.locationPending, 3); a.equal(log.locationRechecks.length, 3);
const rev = JSON.parse(fs.readFileSync(path.join(root, 'game-release.json'), 'utf8')).revision;
a.equal(rev, '20261106-restaurants-slot19-1');
a.ok(fs.readFileSync(path.join(directory, 'index.html'), 'utf8').includes('app.js?v=' + rev));
a.ok(fs.readFileSync(path.join(root, 'world.html'), 'utf8').includes('world-game-assets.js?v=' + rev));
a.match(fs.readFileSync(path.join(root, 'world-game-assets.js'), 'utf8'), /restaurants:'1\.9\.26'/);
console.log('restaurant slot19 verified');
