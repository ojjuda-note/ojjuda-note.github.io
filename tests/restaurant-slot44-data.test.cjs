'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const file = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
const db = file('games/certified-restaurants/restaurants.json');
const supplement = file('games/certified-restaurants/official-gyeongnam-slot44.json');
const sources = file('games/certified-restaurants/sources.json');
const audit = file('ops/restaurant-region-audit.json');
const app = fs.readFileSync(path.join(root, 'games/certified-restaurants/app.js'), 'utf8');
const assets = fs.readFileSync(path.join(root, 'shared/games/world-game-assets.js'), 'utf8');
const world = fs.readFileSync(path.join(root, 'world.html'), 'utf8');
const index = fs.readFileSync(path.join(root, 'games/certified-restaurants/index.html'), 'utf8');

assert.equal(supplement.updatedAt, '2026-11-07');
assert.equal(supplement.restaurants.length, 1, 'only official KTO-backed restaurant imported');
const [newPlace] = supplement.restaurants;
assert.equal(newPlace.id, 'local-sacheon-slot44-samcheonpo-jeongseobang');
assert.equal(newPlace.name, '삼천포맛집정서방');
assert.equal(newPlace.address, '경상남도 사천시 진삼로 269');
assert.equal(newPlace.region, '경남');
assert.equal(newPlace.lat, null);
assert.equal(newPlace.lng, null);
assert.ok(!db.restaurants.some(place => place.id === newPlace.id || (place.name === newPlace.name && place.address === newPlace.address)));
assert.equal(newPlace.guides.length, 1);
assert.equal(newPlace.guides[0].provider, 'local-guide');
assert.equal(newPlace.guides[0].year, null);
assert.equal(newPlace.guides[0].yearType, 'listing');
assert.match(newPlace.guides[0].sourceUrl, /^https:\/\/korean\.visitkorea\.or\.kr\/detail\/ms_detail\.do\?cotid=/);

assert.equal(supplement.locationEnrichments.length, 1);
const [patch] = supplement.locationEnrichments;
assert.equal(patch.id, 'post-2026-45-0-0');
const original = db.restaurants.find(place => place.id === patch.id);
assert.ok(original, 'existing saved ID is retained');
assert.equal(original.name, patch.expectedName);
assert.equal(original.address, patch.expectedAddress);
assert.equal(original.lat, null);
assert.equal(original.lng, null);
assert.ok(original.guides.some(guide => guide.provider === 'post-office'));
assert.ok(patch.lat > 35.0 && patch.lat < 35.4 && patch.lng > 128.0 && patch.lng < 128.2);
assert.match(patch.coordinateSource.url, /^https:\/\/smi\.purpleo\.kr\/article\/19209$/);

assert.ok(app.includes('slot44.restaurants'), 'the live directory loads the new local listing');
assert.ok(app.includes('slot44.locationEnrichments'), 'the live directory applies the verified coordinates');
assert.ok(app.includes('row.id === patch.id && row.name === patch.expectedName && row.address === patch.expectedAddress'), 'the map location is tied to an exact place');
assert.ok(app.includes('restaurant.lat != null || restaurant.lng != null'), 'previous coordinates are never overwritten');
assert.equal(sources.coverage.uniqueRestaurants, 3270);
assert.equal(sources.coverage.coordinatesAvailable, sources.latestMapCoverageAudit.currentCoverage.coordinatesAvailable);
assert.equal(sources.coverage.coordinatesMissing, sources.latestMapCoverageAudit.currentCoverage.coordinatesMissing + 20, 'new official listings have no guessed coordinates');
assert.equal(sources.coverage.coordinatesAvailable + sources.coverage.coordinatesMissing, sources.coverage.uniqueRestaurants);
assert.equal(sources.coverage.providerCounts['local-guide'], 2539);
const slot44 = audit.entries.find(item => item.cycle === 1 && item.slot === 44);
assert.ok(slot44);
assert.equal(slot44.additions, 1);
assert.equal(slot44.modifications, 1);
assert.equal(slot44.locationCoordinatesAdded, 1);
assert.equal(slot44.locationHidden, 0);
assert.equal(slot44.locationPending, 4);
assert.equal(slot44.locationRechecks.length, 4);
assert.deepEqual(slot44.nextRegions, ['경상남도 통영시', '경상남도 거제시']);

const release = file('game-release.json');
assert.ok(assets.includes("const revision='" + release.revision + "'"));
assert.ok(world.includes('world-game-assets.js?v=' + release.revision));
assert.match(index, /\.\/app\.js\?v=\d{8}-[a-z0-9-]+/, 'the restaurant entry point keeps its own cache revision when another game is released');
// Later slots must preserve historical source records while adding exact official locations.
const seogwipo = file('games/certified-restaurants/official-jeju-slot48-locations.json');
assert.equal(seogwipo.cycle, 1);
assert.equal(seogwipo.slot, 48);
assert.deepEqual(seogwipo.restaurants, [], 'all verified locations reuse existing certified IDs');
assert.equal(seogwipo.locationEnrichments.length, 6);
assert.equal(new Set(seogwipo.locationEnrichments.map(item => item.id)).size, 6);
for (const candidate of seogwipo.locationEnrichments) {
  const original = db.restaurants.find(item => item.id === candidate.id);
  assert.ok(original, 'only known saved IDs get new coordinates');
  assert.equal(original.name, candidate.expectedName);
  assert.equal(original.address, candidate.expectedAddress);
  assert.equal(original.region, '제주');
  assert.equal(original.district, '서귀포시');
  assert.equal(original.lat, null); assert.equal(original.lng, null);
  assert.ok(original.guides.some(guide => guide.provider === 'blue-ribbon' || guide.provider === 'local-guide'));
  assert.ok(Number.isFinite(candidate.lat) && candidate.lat > 33 && candidate.lat < 34);
  assert.ok(Number.isFinite(candidate.lng) && candidate.lng > 126 && candidate.lng < 127);
  assert.match(candidate.coordinateSource.url, /^https:\/\/www\.visitjeju\.net\/kr\/detail\/view\?contentsid=(?:CNTS_|CONT_)/);
  assert.equal(candidate.coordinateSource.checkedAt, '2026-11-07');
}
const seogwipoCoverage = sources.mapCoverageAuditHistory.find(item => item.cycle === 1 && item.slot === 48);
assert.ok(seogwipoCoverage, 'the original slot48 official coordinate reconciliation remains preserved');
assert.equal(seogwipoCoverage.currentCoverage.coordinatesAvailable, 1051);
assert.equal(seogwipoCoverage.currentCoverage.coordinatesMissing, 2199);
const slot48 = audit.entries.find(item => item.cycle === 1 && item.slot === 48);
assert.ok(slot48, 'later slots must retain prior slot48 audit');
assert.equal(slot48.locationPending, 16);
assert.ok(app.includes('slot48Seogwipo.locationEnrichments'), 'the live app uses verified overlay');
assert.match(assets, /restaurants:'\d+\.\d+\.\d+'/, 'the restaurant game has an independent release version');
console.log('restaurant slot44 Jinju/Sacheon official listing and location checks passed');
