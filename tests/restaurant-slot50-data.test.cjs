'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const load = p => JSON.parse(fs.readFileSync(path.join(root,p),'utf8'));
const read = p => fs.readFileSync(path.join(root,p),'utf8');
const file = load('games/certified-restaurants/official-gangwon-slot50.json');
const source = load('games/certified-restaurants/sources.json');
const audit = load('ops/restaurant-region-audit.json');
const app = read('games/certified-restaurants/app.js');
const release = load('game-release.json');
assert.equal(file.cycle,1);assert.equal(file.slot,50);assert.equal(file.restaurants.length,5);
assert.equal(new Set(file.restaurants.map(x=>x.id)).size,5);
assert.equal(file.restaurants.filter(x=>x.district==='춘천시').length,3);
assert.equal(file.restaurants.filter(x=>x.district==='고성군').length,2);
for (const row of file.restaurants) {
 assert.equal(row.region,'강원');assert.ok(row.address.startsWith('강원특별자치도 '+row.district+' '));
 if(row.district==='춘천시'){
  assert.ok(Number.isFinite(row.lat)&&Number.isFinite(row.lng),'official city map coordinates exist: '+row.name);
  assert.equal(row.coordinateSourceUrl,row.addressSourceUrl);
  assert.equal(row.coordinateSourceCheckedAt,'2026-11-10');
 }else{assert.equal(row.lat,null);assert.equal(row.lng,null);}
 assert.equal(row.guides.length,1);assert.equal(row.guides[0].provider,'local-guide');
 assert.equal(row.guides[0].year,null);assert.equal(row.guides[0].status,'official_tourism_listing');
 assert.match(row.guides[0].sourceUrl,/^https:\/\/(www.chuncheon.go.kr|korean.visitkorea.or.kr)\//);
}
assert.ok(app.includes('...slot50Gangwon.restaurants'));
assert.ok(app.includes('official-gangwon-slot50.json?v='+release.revision));
const historical = source.coverageAuditHistory.find(x => x.id === '2026-11-07-gangwon-slot50-five-official-tourism-introductions');
assert.ok(historical, 'the original slot 50 coverage snapshot is preserved');
assert.equal(historical.currentCoverage.uniqueRestaurants,3275);
assert.equal(historical.currentCoverage.providerCounts['local-guide'],2544);
assert.equal(historical.currentCoverage.regionalCounts['강원'],66);
assert.equal(historical.currentCoverage.coordinatesAvailable,1052);
assert.equal(historical.currentCoverage.coordinatesMissing,2223);
assert.ok(source.coverage.uniqueRestaurants >= historical.currentCoverage.uniqueRestaurants);
assert.equal(Object.values(source.coverage.categoryCounts).reduce((x,y)=>x+y,0),source.coverage.uniqueRestaurants);
const entry=audit.entries.filter(x=>x.cycle===1&&x.slot===50);
assert.equal(entry.length,1);assert.equal(entry[0].additions,5);assert.equal(entry[0].modifications,0);
assert.equal(entry[0].locationCoordinatesAdded,0);assert.equal(entry[0].locationHidden,0);
assert.equal(entry[0].locationPending,56);assert.equal(entry[0].pendingLocationInventory.length,56);
assert.ok(entry[0].pendingLocationInventory.every(x=>x.restaurantId&&x.name&&x.currentAddress&&x.region&&x.recheckCycle===2));
assert.ok(audit.active.cycle > 1 || (audit.active.cycle === 1 && audit.active.slot >= 50));
assert.ok(source.latestCoverageAudit.cycle > 1 || (source.latestCoverageAudit.cycle === 1 && source.latestCoverageAudit.slot >= 50));
assert.match(release.revision, /^\d{8}-[a-z0-9-]+$/);
assert.ok(read('world.html').includes('world-game-assets.js?v='+release.revision));
const restaurantRevision=read('games/certified-restaurants/index.html').match(/app\.js\?v=(\d{8}-restaurants-[a-z0-9-]+)/)?.[1];
assert.ok(restaurantRevision,'restaurant app keeps its own cache revision');
assert.ok(read('games/certified-restaurants/world-restaurant-guide.js').includes('index.html?v='+restaurantRevision));
assert.match(read('shared/games/world-game-assets.js'), /restaurants:'\d+\.\d+\.\d+'/);
console.log('Gangwon 1/50 official source and safe-location checks passed');
