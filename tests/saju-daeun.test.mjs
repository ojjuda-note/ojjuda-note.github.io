import test from 'node:test';
import assert from 'node:assert/strict';
import { calculateSaju } from '../games/starlit-saju/engine.mjs';
import { analyzeDaeun, DaeunInputError } from '../games/starlit-saju/daeun.mjs';
import { getTenGod, interactionPairs, makeProfile } from '../games/starlit-saju/fortune-data.mjs';
import { Solar } from '../games/starlit-saju/vendor/lunar-1.7.8.mjs';

const NOW = new Date('2026-11-13T00:00:00Z');
const birth = input => calculateSaju(input, { now: NOW });
const analyze = (chart, options = {}) => analyzeDaeun(chart, { gender: 'male', now: NOW, ...options });
const base = birth({ year: 2005, month: 12, day: 23, hour: 8, minute: 37 });

// Golden dates are published by the upstream maintainer, not generated by this
// wrapper: 6tail/lunar-javascript@5c92e62c904ba5cc0b62f032796aeef433702268
// __tests__/Yun.test.js test5 and test6. Upstream clocks are UTC+8; our inputs
// are one hour later, representing the same instant in Korea.
test('sect2 agrees with the pinned official forward golden example', () => {
  const chart = birth({ year: 2022, month: 3, day: 9, hour: 21, minute: 51 });
  const result = analyze(chart);
  assert.equal(result.available, true);
  assert.equal(result.direction, 'forward');
  assert.deepEqual([result.startAge.years, result.startAge.months, result.startAge.days, result.startAge.hours], [8, 9, 2, 10]);
  assert.equal(result.startsAt, '2030-12-12T07:51:00+09:00');
  assert.deepEqual(result.periods.map(value => value.hanja), ['甲辰', '乙巳', '丙午', '丁未', '戊申', '己酉', '庚戌', '辛亥', '壬子']);
  assert.equal(result.referenceTerm.term, '청명');
  assert.equal(result.currentState, 'before-start');
  assert.equal(result.currentIndex, null);
  assert.equal(result.periods[0].startAgeYears, 8);
});

test('sect2 agrees with the pinned official reverse golden example', () => {
  const chart = birth({ year: 2018, month: 6, day: 11, hour: 10, minute: 30 });
  const result = analyze(chart, { gender: 'female' });
  assert.equal(result.direction, 'reverse');
  assert.equal(result.startsAt, '2020-03-21T12:30:00+09:00');
  assert.deepEqual([result.startAge.years, result.startAge.months, result.startAge.days, result.startAge.hours], [1, 9, 10, 2]);
  assert.deepEqual(result.periods.map(value => value.hanja), ['丁巳', '丙辰', '乙卯', '甲寅', '癸丑', '壬子', '辛亥', '庚戌', '己酉']);
  assert.equal(result.referenceTerm.term, '망종');
  assert.equal(result.currentIndex, 1);
  assert.equal(result.periods[0].startAgeYears, 1); // Not the upstream nominal age 3.
});

test('all four traditional year-stem and gender direction combinations are explicit', () => {
  for (const [year, gender, direction, firstPair] of [
    [2024, 'male', 'forward', '辛未'], [2024, 'female', 'reverse', '己巳'],
    [2023, 'male', 'reverse', '丁巳'], [2023, 'female', 'forward', '己未'],
  ]) {
    const result = analyze(birth({ year, month: 6, day: 15, hour: 12 }), { gender });
    assert.equal(result.direction, direction, `${year} ${gender}`);
    assert.equal(result.periods[0].hanja, firstPair, `${year} ${gender}`);
    assert.equal(result.periods.length, 9);
  }
});

test('year direction follows Korean Lichun, not January 1 or a shifted day pillar', () => {
  const january = birth({ year: 2024, month: 1, day: 1, hour: 0, minute: 30 });
  assert.equal(january.pillars[0].hanja, '癸卯');
  assert.equal(analyze(january).direction, 'reverse');
  const before = birth({ year: 2024, month: 2, day: 4, hour: 17, minute: 26 });
  const after = birth({ year: 2024, month: 2, day: 4, hour: 17, minute: 28 });
  assert.equal(analyze(before).direction, 'reverse');
  assert.equal(analyze(after).direction, 'forward');
  assert.equal(after.pillars[0].hanja, '甲辰');
  const midnight = birth({ year: 1981, month: 1, day: 30, hour: 0, minute: 37 });
  const result = analyze(midnight, { gender: 'female' });
  assert.equal(result.startsAt, '1989-02-26T02:37:00+09:00');
  const chinaDay = Solar.fromYmdHms(1981, 1, 29, 23, 37, 0).getLunar().getEightChar().getDayGan();
  assert.notEqual(midnight.dayMaster.hanja, chinaDay, 'fixture crosses a day-stem boundary');
  for (const period of result.periods) {
    assert.deepEqual(period.stemGod, getTenGod(midnight.dayMaster, period.stem));
    assert.deepEqual(period.branchGod, getTenGod(midnight.dayMaster, period.branchMainStem));
  }
});

test('Korean month-end calendar addition is not incorrectly done in UTC+8', () => {
  const result = analyze(birth({ year: 1990, month: 1, day: 31, hour: 0, minute: 30 }), { gender: 'female' });
  assert.deepEqual([result.startAge.years, result.startAge.months, result.startAge.days, result.startAge.hours], [1, 5, 23, 16]);
  // Jan 31 + 1 year + 5 months = June 30 (month-end clipping); +23d +16h.
  assert.equal(result.startsAt, '1991-07-23T16:30:00+09:00');
  assert.notEqual(result.startsAt, '1991-07-24T16:30:00+09:00');
});

test('missing gender, unknown time and a boundary minute never receive fabricated periods', () => {
  const cases = [
    [base, { gender: null }, 'gender-required'],
    [birth({ year: 2005, month: 12, day: 23, hour: null }), {}, 'birth-time-required'],
    [birth({ year: 2024, month: 2, day: 4, hour: 17, minute: 27 }), {}, 'solar-term-uncertain'],
    [birth({ year: 2024, month: 2, day: 4, hour: null }), {}, 'birth-time-required'],
  ];
  for (const [chart, options, reason] of cases) {
    const result = analyze(chart, options);
    assert.equal(result.available, false);
    assert.equal(result.reason, reason);
    assert.equal(result.startsAt, null);
    assert.equal(result.startAge, null);
    assert.equal(result.direction, null);
    assert.equal(result.currentIndex, null);
    assert.deepEqual(result.periods, []);
    assert.deepEqual(result.facts, []);
    assert.ok(result.message);
  }
  const midnight = analyze(birth({ year: 2005, month: 12, day: 23, hour: 0 }));
  assert.equal(midnight.available, true, 'known midnight differs from unknown time');
});

test('current periods include the start and exclude the end, with contiguous ten-year boundaries', () => {
  const first = analyze(base);
  for (let offset = 0; offset < first.periods.length; offset++) {
    const period = first.periods[offset];
    const atStart = analyze(base, { now: new Date(period.startsAt) });
    assert.equal(atStart.currentIndex, period.index);
    assert.equal(atStart.periods.filter(value => value.isCurrent).length, 1);
    const justBefore = analyze(base, { now: new Date(Date.parse(period.startsAt) - 1) });
    assert.equal(justBefore.currentIndex, offset === 0 ? null : period.index - 1);
    const atEnd = analyze(base, { now: new Date(period.endsAt) });
    assert.equal(atEnd.currentIndex, offset === first.periods.length - 1 ? null : period.index + 1);
    if (offset + 1 < first.periods.length) assert.equal(period.endsAt, first.periods[offset + 1].startsAt);
    assert.equal(Number(period.endsAt.slice(0, 4)) - Number(period.startsAt.slice(0, 4)), 10);
  }
  assert.equal(analyze(base, { now: new Date(first.periods.at(-1).endsAt) }).currentState, 'after-listed-periods');
});

test('period facts and actual natal interactions retain the full inputs for the reader', () => {
  const result = analyze(base), profile = makeProfile(base);
  const ids = new Set(result.facts.map(value => value.id));
  assert.equal(ids.size, result.facts.length);
  for (const item of result.facts) {
    assert.equal(item.origin, 'calculation');
    assert.equal(typeof item.label, 'string');
    assert.equal(typeof item.value, 'string');
  }
  for (const period of result.periods) {
    assert.ok(period.factIds.every(id => ids.has(id)));
    const expected = profile.knownPillars.flatMap(pillar => interactionPairs(pillar, period, {
      birthPillarKey: pillar.key, birthPillarLabel: pillar.label,
      transitLabel: `${period.index}번째 대운`, otherPillarLabel: `${period.index}번째 대운`,
    }));
    assert.deepEqual(period.interactions, expected);
    assert.deepEqual(period.branchGod, getTenGod(profile.dayMaster, period.branchMainStem));
  }
  assert.ok(result.method.notes.some(value => value.includes('만 나이')));
  assert.equal(result.method.sect, 2);
  assert.equal(result.sources.length, 3);
});

test('invalid input fails instead of silently substituting a gender, birthday or clock', () => {
  for (const gender of ['', 'unknown', 0, 1, false]) assert.throws(() => analyze(base, { gender }), DaeunInputError);
  for (const now of [null, '2026-11-13', new Date(NaN)]) assert.throws(() => analyze(base, { now }), DaeunInputError);
  for (const change of [
    chart => { delete chart.solar; },
    chart => { chart.solar.day = 32; },
    chart => { chart.solar.month = 2; chart.solar.day = 30; },
    chart => { chart.input.hour = 24; },
    chart => { chart.input.minute = 60; },
    chart => { chart.timeKnown = false; },
    chart => { chart.pillars.pop(); },
    chart => { chart.pillars.push(chart.pillars[0]); },
    chart => { chart.dayMaster.hanja = '甲'; },
    chart => { chart.pillars[0].hanja = '甲子'; },
    chart => { chart.pillars[1].hanja = '甲丑'; },
  ]) {
    const chart = structuredClone(base); change(chart);
    assert.throws(() => analyze(chart), DaeunInputError);
  }
  assert.throws(() => analyze(null), DaeunInputError);
  assert.throws(() => analyze(base, { now: new Date('2000-01-01T00:00:00Z') }), DaeunInputError);
});

test('chart, name, clock and independent outputs remain unchanged across calculations', () => {
  const freeze = value => { if (value && typeof value === 'object') { Object.values(value).forEach(freeze); Object.freeze(value); } return value; };
  const chart = structuredClone(base);
  chart.name = '표시만 하는 이름'; chart.input.name = '계산에 사용하지 않음';
  const before = JSON.stringify(chart), nowTime = NOW.getTime();
  freeze(chart);
  const result = analyze(chart);
  assert.equal(JSON.stringify(chart), before);
  assert.equal(NOW.getTime(), nowTime);
  assert.deepEqual(result, analyze(base));
  assert.deepEqual(result, analyze(chart));
  result.method.notes.push('변경'); result.sources[0].title = '변경';
  const next = analyze(chart);
  assert.notEqual(next.sources[0].title, '변경');
  assert.equal(next.method.notes.includes('변경'), false);
  const otherGender = analyze(chart, { gender: 'female' });
  assert.notEqual(otherGender.direction, next.direction);
  assert.notEqual(otherGender.startsAt, next.startsAt);
  assert.equal(JSON.stringify(chart), before);
});
