const NOW = new Date('2026-11-13T00:00:00Z');
const birth = input => calculateSaju(input, { now: NOW });
const analyze = (chart, options = {}) => analyzeDaeun(chart, { gender: 'male', now: NOW, ...options });
const base = birth({ year: 2005, month: 12, day: 23, hour: 8, minute: 37 });

// Golden dates are published by the upstream maintainer, not generated by this
// wrapper: 6tail/lunar-javascript@5c92e62c904ba5cc0b62f032796aeef433702268
// __tests__/Yun.test.js test5 and test6. Upstream clocks are UTC+8; our inputs
// are one hour later, representing the same instant in Korea.
test('sect2 agrees with the pinned official forward golden example', () => {
  const chart = birth({ year: 2022, month: 3, day: 9, hour: 21, minute: 51 });
  const result = analyze(chart);
  assert.equal(result.available, true);
  assert.equal(result.direction, 'forward');
  assert.deepEqual([result.startAge.years, result.startAge.months, result.startAge.days, result.startAge.hours], [8, 9, 2, 10]);
  assert.equal(result.startsAt, '2030-12-12T07:51:00+09:00');
  assert.deepEqual(result.periods.map(value => value.hanja), ['甲辰', '乙巳', '丙午', '丁未', '戊申', '己酉', '庚戌', '辛亥', '壬子']);
  assert.equal(result.referenceTerm.term, '청명');
  assert.equal(result.currentState, 'before-start');
  assert.equal(result.currentIndex, null);
  assert.equal(result.periods[0].startAgeYears, 8);
});

