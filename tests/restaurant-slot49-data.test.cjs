'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const file = name => JSON.parse(fs.readFileSync(path.join(root, name), 'utf8'));
const text = name => fs.readFileSync(path.join(root, name), 'utf8');
const supplement = file('games/certified-restaurants/official-gyeonggi-slot49.json');
const original = file('games/certified-restaurants/restaurants.json');
const sources = file('games/certified-restaurants/sources.json');
const audit = file('ops/restaurant-region-audit.json');
const app = text('games/certified-restaurants/app.js');
const assets = text('shared/games/world-game-assets.js');
const world = text('world.html');
const index = text('games/certified-restaurants/index.html');
const frame = text('games/certified-restaurants/world-restaurant-guide.js');
const release = file('game-release.json');
assert.equal(supplement.updatedAt, '2026-11-07');
assert.equal(supplement.restaurants.length, 13);
assert.equal(new Set(supplement.restaurants.map(item => item.id)).size, 13);
assert.equal(supplement.restaurants.filter(item => item.district === '구리시').length, 6);
assert.equal(supplement.restaurants.filter(item => item.district === '평택시').length, 7);
const normalize = value => String(value || '').replace(/\s/g, '').replace(/[·‧]/g, '').toLowerCase();
const allPrior = [...original.restaurants];
for (const name of ['official-gyeonggi-oldshops-slot08.json', 'official-seongnam-hipstores-slot09.json', 'official-goyang-paju-slot10.json', 'official-bucheon-gimpo-slot11.json', 'official-gyeonggi-slot12.json', 'official-gyeonggi-slot13.json', 'official-guri-slot15.json', 'official-gyeonggi-slot17.json']) {
  allPrior.push(...file('games/certified-restaurants/' + name).restaurants);
}
for (const restaurant of supplement.restaurants) {
  assert.ok(restaurant.id.startsWith('local-gyeonggi-slot49-'));
  assert.equal(restaurant.region, '경기');
  assert.equal(restaurant.lat, null);
  assert.equal(restaurant.lng, null);
  assert.ok(restaurant.address.startsWith('경기도 '));
  assert.equal(restaurant.guides.length, 1);
  const [guide] = restaurant.guides;
  assert.equal(guide.provider, 'local-guide');
  assert.equal(guide.status, 'official_restaurant_listing');
  assert.equal(guide.year, null, 'publication year is not selection year');
  assert.equal(guide.yearType, 'source');
  assert.match(guide.sourceUrl, /^https:\/\/gnews\.gg\.go\.kr\//);
  assert.ok(guide.sourceAsOf === '2026-01-27' || guide.sourceAsOf === '2025-08-21');
  assert.ok(!allPrior.some(other => other.id === restaurant.id || (normalize(other.name) === normalize(restaurant.name) && normalize(other.address) === normalize(restaurant.address))), restaurant.name + ' should not duplicate a previous listing');
}
assert.ok(app.includes('official-gyeonggi-slot49.json?v=' + release.revision), 'new file has a separate cache revision');
assert.ok(app.includes('...slot49Gyeonggi.restaurants'), 'new local official entries are merged in the live catalog');
assert.ok(app.includes('knownIds.has(item.id) || knownPlaces.has(key)'), 'the live directory retains its duplicate guard');
assert.equal(sources.coverage.uniqueRestaurants, 3263);
assert.equal(sources.coverage.providerCounts['local-guide'], 2532);
assert.equal(sources.coverage.regionalCounts['경기'], 395);
assert.equal(sources.coverage.coordinatesAvailable, 1052);
assert.equal(sources.coverage.coordinatesMissing, 2211);
assert.equal(Object.values(sources.coverage.categoryCounts).reduce((a,b) => a+b, 0), 3263);
assert.equal(sources.latestCoverageAudit.slot, 49);
assert.equal(sources.latestCoverageAudit.newRestaurantCount, 13);
const entry = audit.entries.filter(item => item.cycle === 1 && item.slot === 49);
assert.equal(entry.length, 1, 'do not apply one scheduled slot twice');
assert.equal(entry[0].additions, 13);
assert.equal(entry[0].modifications, 0);
assert.equal(entry[0].locationCoordinatesAdded, 0);
assert.equal(entry[0].locationHidden, 0);
assert.equal(entry[0].locationPending, 342);
assert.equal(entry[0].pendingLocationInventory.length, 342);
assert.ok(entry[0].pendingLocationInventory.every(item => item.restaurantId && item.name && item.currentAddress && item.region && item.recheckCycle === 2));
assert.equal(audit.active.slot, 49);
assert.equal(release.revision, '20261107-restaurants-slot49-gg13');
assert.ok(assets.includes("const revision='" + release.revision + "'"));
assert.ok(assets.includes("restaurants:'1.11.8'"));
assert.ok(world.includes('world-game-assets.js?v=' + release.revision));
