const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {randomUUID}=require('node:crypto'),{PGlite}=require('@electric-sql/pglite');
(async()=>{const db=new PGlite(),user=randomUUID(),other=randomUUID(),run=randomUUID();
 try{
  await db.exec(`create role anon;create role authenticated;create schema auth;create schema ojjuda_note_internal;
   create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;
   create table public.user_private(user_id uuid primary key,coins integer not null check(coins>=0),banned boolean default false);
   create function public.is_banned(uuid) returns boolean language sql stable as $$select coalesce((select banned from public.user_private where user_id=$1),false)$$;
   create table ojjuda_note_internal.spend_requests(request_id uuid primary key,user_id uuid not null,kind text not null,coins integer not null,result jsonb not null);
   grant usage on schema public,auth to anon,authenticated;
   insert into public.user_private(user_id,coins) values('${user}',30),('${other}',50);`);
  const folder=path.join(__dirname,'../supabase/migrations');
  const migration=fs.readdirSync(folder).find(x=>x.endsWith('_sacheonseong_paid_tools.sql'));
  await db.exec(fs.readFileSync(path.join(folder,migration),'utf8'));
  const buy=async(kind,id=randomUUID(),runId=run,stage=5,verify=false)=>(await db.query('select public.sacheonseong_tool_buy($1,$2,$3,$4,$5) v',[kind,id,runId,stage,verify])).rows[0].v;
  const auth=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id||'']);await db.exec('set role authenticated');};
  const setBalance=async n=>{await db.exec('reset role');await db.query('update public.user_private set coins=$1 where user_id=$2',[n,user]);await db.exec('set role authenticated');};
  await db.exec('set role anon');await assert.rejects(()=>buy('hint'),/permission denied/);
  await auth(null);await assert.rejects(()=>buy('hint'),/not_signed_in/);
  await auth(user);
  const hint=randomUUID(),shuffle=randomUUID();
  let r=await buy('hint',hint);assert.equal(r.price,3);assert.equal(r.coins,27);
  assert.equal((await buy('hint',hint)).coins,27,'same receipt cannot charge twice');
  r=await buy('shuffle',shuffle);assert.equal(r.price,10);assert.equal(r.coins,17);
  assert.equal((await buy('shuffle',shuffle)).coins,17);
  assert.equal((await buy('hint',hint,randomUUID())).reason,'request_conflict');
  assert.equal((await buy('hint',hint,run,6)).reason,'request_conflict');
  assert.equal((await buy('shuffle',hint)).reason,'request_conflict');
  assert.equal((await buy('hint',randomUUID(),run,5,true)).reason,'not_found');
  for(const [kind,stage] of [[null,1],['free',1],['hint',0],['shuffle',16]])assert.equal((await buy(kind,randomUUID(),run,stage)).reason,'invalid');
  await auth(other);assert.equal((await buy('hint',hint)).reason,'request_conflict');
  await auth(user);await setBalance(2);assert.equal((await buy('hint')).reason,'coins');
  await setBalance(9);r=await buy('shuffle');assert.equal(r.reason,'coins');assert.equal(r.price,10);assert.equal(r.coins,9);
  await setBalance(10);r=await buy('shuffle');assert.equal(r.coins,0);assert.equal(r.price,10);
  await setBalance(3);const results=await Promise.all([buy('hint'),buy('hint')]);assert.equal(results.filter(x=>x.ok).length,1);assert.equal(results.find(x=>!x.ok).reason,'coins');
  await db.exec('reset role');await db.query('update public.user_private set banned=true,coins=30 where user_id=$1',[user]);await db.exec('set role authenticated');assert.equal((await buy('hint')).reason,'banned');
  await assert.rejects(()=>db.exec('update public.user_private set coins=999'),/permission denied/);
  await assert.rejects(()=>db.exec('select * from ojjuda_note_internal.spend_requests'),/permission denied/);
  await db.exec('reset role');const rows=(await db.query('select kind,coins from ojjuda_note_internal.spend_requests')).rows;
  assert(rows.every(r=>r.coins===(r.kind==='sacheonseong_hint'?3:10)));
  console.log('PASS: hint 3 / shuffle 10, exact-once receipts, insufficient funds, zero balance, read-only verification, conflicts, banned/anonymous users and private wallet permissions.');
 }finally{await db.close();}
})().catch(e=>{console.error(e);process.exitCode=1});
