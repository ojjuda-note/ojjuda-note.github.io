const unique = values => [...new Set(values)];

export function buildReaderSituation({topic,codes,natalCodes,interactions=[],periodLabel='평소'}={}) {
  if(!Object.hasOwn(SITUATIONS,topic)||!Array.isArray(codes)||!codes.length||codes.length>2
    ||!Array.isArray(natalCodes)||!natalCodes.length||natalCodes.length>2
    ||[...codes,...natalCodes].some(code=>!Object.hasOwn(NATAL_CONTEXTS,code))
    ||!Array.isArray(interactions)||interactions.some(value=>!['stem-combination','branch-combination','branch-clash'].includes(value?.kind))
    ||typeof periodLabel!=='string'||!periodLabel.trim())throw new Error('확인된 성향과 시기로 생활 장면을 다시 준비해 주세요.');
  const actualCodes=unique(codes),actualNatalCodes=unique(natalCodes),[first,second]=actualCodes;
  const [natalFirst,natalSecond]=actualNatalCodes,scenario=SITUATIONS[topic][first];
  const natal=NATAL_CONTEXTS[natalFirst][topic];
  const connect=interactions.some(value=>value.kind!=='branch-clash'),clash=interactions.some(value=>value.kind==='branch-clash');
  const interactionKind=connect&&clash?'both':clash?'clash':connect?'connect':null;
  const periodOpening=periodLabel==='평소'?'평소에는':`${periodLabel}에는`;
  const paragraphs=[
    `${periodOpening} ${scenario.meaning}`,
    natal[0],
    scenario.condition+(second?` ${SECONDARY_CONDITIONS[second][topic]}`:''),
    scenario.boundary+(interactionKind?` ${INTERACTION_CONTEXTS[topic][interactionKind]}`:''),
    `가령 ${scenario.example}`,
    `${scenario.action} ${natal[1]}`+(natalSecond?` ${NATAL_CONTEXTS[natalSecond][topic][1]}`:''),
  ];
  return {
    title:scenario.title,paragraphs,godCodes:actualCodes,natalGodCodes:actualNatalCodes,interactionKind,
    origin:'service-reference',
    ruleIds:[`situation.${topic}.${first}`,`reaction.${topic}.${natalFirst}`,
      ...(second?[`condition.${topic}.${second}`]:[]),...(natalSecond?[`adjustment.${topic}.${natalSecond}`]:[]),
      ...(interactionKind?[`interaction.${topic}.${interactionKind}`]:[])],
  };
}
