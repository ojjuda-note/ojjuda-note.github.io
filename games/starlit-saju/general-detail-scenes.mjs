/** Keep the readable sections and the complete, ordered copy as one contract. */
export function detailContent(groups) {
  const detailSections=groups.map(([title,values])=>({title,paragraphs:values.filter(Boolean)})).filter(section=>section.paragraphs.length);
  if(detailSections.some(section=>typeof section.title!=='string'||!section.title.trim()
    ||section.paragraphs.some(value=>typeof value!=='string'||!value.trim())))throw new TypeError('자세한 풀이의 문단을 확인해 주세요.');
  return {paragraphs:detailSections.flatMap(section=>section.paragraphs),detailSections};
}

