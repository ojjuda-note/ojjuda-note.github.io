const RANKS = ['ace','two','three','four','five','six','seven','eight','nine','ten','page','knight','queen','king'];
const RANK_NAMES = ['에이스','2','3','4','5','6','7','8','9','10','시종','기사','여왕','왕'];
const NUMERALS = ['A','II','III','IV','V','VI','VII','VIII','IX','X','P','KN','Q','K'];

function makeCard(d) {
  const minor = Boolean(d.suit);
  const number = minor ? d.index + 1 : d.number;
  const suitName = d.suit === 'wands' ? '완드' : '컵';
  const rank = minor ? RANKS[d.index] : undefined;
  const name = minor ? `${suitName} ${RANK_NAMES[d.index]}` : d.name;
  const topics = {}, details = {};
  for (const topic of ['overall','love','money','work']) {
    const [context, example, action] = d.readings[topic];
    topics[topic] = `${context} ${d.reflection}`;
    details[topic] = { example, action };
  }
  return {
    id: minor ? `${d.suit}_${rank}` : d.id,
    name,
    english: minor ? `${rank.toUpperCase()} OF ${d.suit.toUpperCase()}` : d.english,
    numeral: minor ? NUMERALS[d.index] : d.numeral,
    keyword: d.keyword,
    color: d.color || (d.suit === 'wands' ? '#e8ae78' : '#99d5df'),
    message: d.message,
    arcana: minor ? 'minor' : 'major', number,
    ...(minor ? { suit: d.suit, rank } : {}),
    art: { src: `./assets/${minor ? d.suit : 'major-extra'}.webp`, columns: minor ? 7 : 5, rows: 2, index: d.index },
    topics,
    guidance: { summary: d.summary, meaning: d.meaning, positions: d.positions, caution: d.caution },
    details,
    step: d.step,
    spread: { tone: d.tone, inner: d.inner, opening: d.opening, direction: d.direction }
  };
}

