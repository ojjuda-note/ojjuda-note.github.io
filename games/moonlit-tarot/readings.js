function resolveCard(card) {
  if (typeof card === 'number') return DECK[card] ?? DECK[0];
  if (typeof card === 'string') return DECK.find(item => item.id === card) ?? DECK[0];
  return card && typeof card === 'object' && card.id
    ? DECK.find(item => item.id === card.id) ?? DECK[0]
    : DECK[0];
}

function resolveTopic(topic) {
  const id = typeof topic === 'object' && topic ? topic.id : topic;
  return typeof id === 'string' && Object.hasOwn(TOPIC_SUMMARIES, id) ? id : 'overall';
}

function resolvePosition(position) {
  if (Number.isInteger(position)) return Math.max(0, Math.min(2, position));
  const id = typeof position === 'object' && position ? position.id : position;
  const index = POSITIONS.findIndex(item => item.id === id);
  return index < 0 ? 0 : index;
}

function sectionsToText(summary, sections) {
  return [summary, ...sections.map(section => `${section.title}\n${section.body}`)].join('\n\n');
}

function objectParticle(text) {
  const last = text.charCodeAt(text.length - 1);
  return last >= 0xac00 && last <= 0xd7a3 && (last - 0xac00) % 28 !== 0 ? '을' : '를';
}

/** Accepts a deck object or id, a topic object or id, and a zero-based position or id. */
export function getReading(card, topic = 'overall', position = 0) {
  const selected = resolveCard(card);
  const topicId = resolveTopic(topic);
  const index = resolvePosition(position);
  const guidance = CARD_GUIDANCE[selected.id] || selected.guidance;
  const detail = (TOPIC_DETAILS[selected.id] || selected.details)[topicId];
  const sections = [
    {
      title: '이 카드가 말하는 뜻',
      body: `${guidance.meaning} ${POSITION_INTROS[index]} ${guidance.positions[index]}`
    },
    { title: '지금 내 상황에 비춰 보면', body: selected.topics[topicId] },
    { title: '생활 속에서는 이런 모습이에요', body: detail.example },
    { title: '오늘 해보면 좋은 일', body: detail.action },
    { title: '기억하면 좋은 점', body: `${guidance.caution} ${TOPIC_REMINDERS[topicId]}` }
  ];
  return {
    title: `${POSITIONS[index].label} · ${selected.name}`,
    keyword: selected.keyword,
    summary: guidance.summary,
    sections,
    text: sectionsToText(guidance.summary, sections),
    whisper: index === 2 ? `“${CARD_STEPS[selected.id] || selected.step}.”` : POSITION_WHISPERS[index]
  };
}

