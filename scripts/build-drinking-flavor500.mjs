import fs from 'node:fs';
import path from 'node:path';
import {catalogRoot,loadDrinkingCatalog,validateDrinkingCatalog} from './lib/drinking-catalogs.mjs';

const directory=path.join(catalogRoot,'supabase/migrations');
const flavors=['mild','spicy'];
const games=['king','truth','minority','imagevote','fingers'];
const selected=process.argv.slice(2).filter(arg=>arg!=='--check');
if(selected.some(kind=>!games.includes(kind)))throw Error('Unknown game');
for(const kind of selected.length?selected:games){
  const file=path.join(catalogRoot,'games/drinking/content/expansions/flavor500',kind+'.json');
  const catalog=JSON.parse(fs.readFileSync(file,'utf8'));
  const entries=[];
  for(const flavor of flavors){
    const cards=catalog[flavor];
    if(!Array.isArray(cards)||cards.length!==500)throw Error(kind+' '+flavor+' must contain exactly 500 cards');
    if(kind==='king'&&cards.filter(card=>card.startsWith('둘이 ')).length!==250)throw Error('King needs 250 solo and 250 two-player orders per flavor');
    for(const card of cards){
      if(kind==='fingers'&&!card.endsWith('사람 접어'))throw Error('Unplayable finger condition: '+card);
      if((kind==='truth'||kind==='imagevote')&&!card.endsWith('?'))throw Error('Question expected: '+card);
      if(kind==='minority'&&card.some(side=>side.length>80))throw Error('Minority ballot exceeds 80 characters');
      entries.push(kind==='truth'?{flavor,body:card}:card);
    }
  }
  validateDrinkingCatalog(kind,[...loadDrinkingCatalog(kind),...entries]);
  const data=JSON.stringify(catalog);
  if(data.includes('$cards$'))throw Error('SQL delimiter in catalog');
  const rows=`from jsonb_each($cards$${data}$cards$::jsonb) as tier(flavor,cards)
 cross join lateral jsonb_array_elements(tier.cards) with ordinality as c(card,n)
 order by tier.flavor,c.n`;
  const insert=kind==='truth'?`with added as (
 insert into ojjuda_arcade_internal.drinking_truth_cards(flavor,body,party_pick)
 select tier.flavor,c.card#>>'{}',true
 ${rows}
 returning id,flavor,body
)
insert into ojjuda_arcade_internal.drinking_truth_history(fingerprint,card_id)
select ojjuda_arcade_internal.drinking_prompt_fingerprint('truth',flavor,body),id from added;`:
`insert into ojjuda_arcade_internal.drinking_content_items(kind,body,second,party_pick,prompt_flavor)
select '${kind}',${kind==='minority'?"c.card->>0,c.card->>1":"c.card#>>'{}',null"},true,tier.flavor
 ${rows};`;
  const sql=`-- Generated by scripts/build-drinking-flavor500.mjs from the reviewed ${kind} catalog.
begin;
select pg_advisory_xact_lock(24613,911);
${insert}
commit;
`;
  const files=fs.readdirSync(directory).filter(f=>f.endsWith('_drinking_flavor500_'+kind+'.sql'));
  if(files.length!==1)throw Error('Expected one flavor500 migration for '+kind);
  const migration=path.join(directory,files[0]);
  if(process.argv.includes('--check')){
    if(fs.readFileSync(migration,'utf8')!==sql)throw Error('Migration differs from '+file);
  }else fs.writeFileSync(migration,sql);
}
