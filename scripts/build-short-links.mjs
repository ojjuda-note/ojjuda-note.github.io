import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const origin = 'https://ojjuda.kr';
const escape = value => String(value).replace(/[&<>"']/g, char => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));

export function buildShortLinks(directory, catalog = JSON.parse(fs.readFileSync(path.join(root, 'shared/navigation/short-links.json'), 'utf8'))) {
  const seen = new Set();
  // Validate every route before writing anything; never replace an existing service.
  for (const route of catalog.routes) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(route.slug) || seen.has(route.slug)) throw Error(`Invalid or duplicate short link: ${route.slug}`);
    seen.add(route.slug);
    const target = new URL(route.target, origin);
    if (!route.target.startsWith('/') || route.target.startsWith('//') || target.origin !== origin || target.pathname === `/${route.slug}/`) throw Error(`Unsafe short link: ${route.slug}`);
    if (route.publishEntry && (!route.target.endsWith('/') || target.search || target.hash)) throw Error(`Service entry must target a directory: ${route.target}`);
    const source = path.join(directory, decodeURIComponent(target.pathname), target.pathname.endsWith('/') ? 'index.html' : '');
    if (!fs.statSync(source, {throwIfNoEntry:false})?.isFile()) throw Error(`Missing short-link destination: ${route.target}`);
    const output = path.join(directory, route.slug, 'index.html');
    if (fs.existsSync(output) && !fs.readFileSync(output, 'utf8').includes('<!-- Generated by build-short-links.mjs -->')) throw Error(`Short link would replace an existing page: ${route.slug}`);
  }
  for (const {slug, target, label, publishEntry} of catalog.routes) {
    const output = path.join(directory, slug, 'index.html');
    fs.mkdirSync(path.dirname(output), {recursive:true});
    if (publishEntry) {
      // Publish the actual service at its canonical address, including its member gate.
      const source = path.join(directory, decodeURIComponent(new URL(target, origin).pathname), 'index.html');
      const entry = fs.readFileSync(source, 'utf8');
      fs.writeFileSync(output, entry.replace(/<!doctype html>/i, '<!doctype html>\n<!-- Generated by build-short-links.mjs -->'));
      continue;
    }
    const html = `<!doctype html>
<!-- Generated by build-short-links.mjs -->
<html lang="ko"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escape(label)} · 오쭈다</title><meta name="robots" content="noindex,follow">
<link rel="canonical" href="${escape(origin + target)}"><link rel="icon" href="/favicon.svg">
<meta name="ojjuda-short-target" content="${escape(target)}">
<script src="/shared/navigation/short-link.js?v=20261118-short1" defer></script>
<noscript><meta http-equiv="refresh" content="0;url=${escape(target)}"></noscript>
<style>body{margin:0;min-height:100vh;display:grid;place-items:center;background:#f7f6ef;color:#263d33;font:16px/1.7 system-ui,sans-serif}main{padding:24px;text-align:center}a{color:#365f47}h1{font-size:22px}</style>
</head><body><main><h1>${escape(label)}</h1><p><a href="${escape(target)}">바로 열기 →</a></p></main></body></html>
`;
    fs.writeFileSync(output, html);
  }
  return catalog.routes.length;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const directory = path.resolve(process.argv[2] || root);
  console.log(`Built ${buildShortLinks(directory)} short links in ${directory}`);
}
